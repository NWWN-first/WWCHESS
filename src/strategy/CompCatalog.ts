export type CompLevelHint = 'reroll5' | 'fast8' | 'fast9';

export interface CompDefinition {
  id: string;
  name: string;
  primaryTrait: TraitId;
  secondaryTraits: TraitId[];
  /** 완성 시 반드시 필요한 핵심 유닛 */
  coreUnitIds: string[];
  /** 교체 가능한 유연 슬롯 */
  flexUnitIds: string[];
  /** 아이템 우선 캐리 */
  carryUnitIds: string[];
  /** 전열/탱크 우선 */
  tankUnitIds: string[];
  levelHint: CompLevelHint;
  /** 스테이지 구간별 상대 파워 편향 0~100 */
  earlyPower: number;
  midPower: number;
  latePower: number;
}

