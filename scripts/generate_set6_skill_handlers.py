def classify(key: str, desc: str) -> str:
    if key in BEHAVIOR:
        return BEHAVIOR[key]
    d = desc.lower()
    if "passive:" in d and "mana" not in d:
        return "single_magic"
    if "all enemies" in d:
        return "all_enemies_magic"
    if "farthest" in d:
        return "farthest_magic"
    if "adjacent" in d or "nearby" in d:
        return "adjacent_aoe_magic"
    if "shield" in d:
        return "self_shield_flat"
    if "heal" in d:
        return "heal_allies_flat"
    if "stun" in d:
        return "single_stun_magic"
    return "single_magic"


